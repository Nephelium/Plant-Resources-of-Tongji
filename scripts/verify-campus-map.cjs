async (page) => {
  const root = page.url().split("#")[0].replace(/\/$/, "") + "/";
  const checks = [], errors = [], tileRequests = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if (r.url().includes("tile.openstreetmap.org")) tileRequests.push(r.url()); });
  const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
  const settle = async () => {
    await page.locator(".campus-basemap").evaluate(img => img.decode());
    await page.waitForFunction(() => !document.querySelector(".page-enter-active,.page-leave-active,.leaflet-zoom-anim"));
    await page.evaluate(() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))));
  };
  const center = () => page.locator(".plant-map").evaluate(el => el.scrollIntoView({ block: "center", behavior: "instant" }));
  const scale = () => page.locator(".leaflet-control-scale-line").innerText();
  const theme = async name => {
    await page.locator(".theme-trigger").click();
    await page.locator(".theme-options").getByRole("button", { name, exact: true }).click();
    await settle();
  };
  const noOverlap = async () => page.locator(".plant-map-shell").evaluate(shell => {
    const labels = [...shell.querySelectorAll(".campus-landmark")].map(el => el.getBoundingClientRect());
    const controls = [...shell.querySelectorAll(".map-base-switch,.map-theme-switch,.map-actions,.leaflet-control")]
      .map(el => el.getBoundingClientRect());
    const intersects = (a, b) => a.left < b.right && a.right > b.left && a.top < b.bottom && a.bottom > b.top;
    return labels.every((rect, i) => !labels.slice(i + 1).some(b => intersects(rect, b)) && !controls.some(b => intersects(rect, b)));
  });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ colorScheme: "light", reducedMotion: "reduce" });
  await page.goto(root + "#/");
  await page.evaluate(() => {
    localStorage.removeItem("tongjiplants_basemap");
    localStorage.removeItem("tongjiplants_theme");
  });
  tileRequests.length = 0;
  await page.reload({ waitUntil: "domcontentloaded" });
  await settle();
  check(await page.getByRole("button", { name: "校园图", exact: true }).getAttribute("aria-pressed") === "true", "首次打开默认校园专属图");
  check(tileRequests.length === 0, "校园图不请求外部地图服务");
  check((await page.locator(".campus-basemap").getAttribute("src")) === new URL("maps/campus-light.svg", root).pathname, "校园资源正确使用部署子目录");
  check((await page.locator(".map-result-count").innerText()).includes("16,440"), "原始与 PDF 补充点位合计 16,440 个");
  check((await page.locator(".stats-strip").innerText()).includes("143"), "补充图例中两种植物后统计为 143 种");
  const names = await page.locator(".campus-landmark").allTextContents();
  check(names.length > 15 && names.some(n => n.includes("A14图书馆")) && names.some(n => n.includes("A05衷和楼")), "总览显示普通楼名、地标与原始楼号");
  check(await noOverlap(), "总览楼名互不重叠并避让控件");
  check(await page.getByRole("checkbox", { name: "滚轮缩放" }).isChecked(), "校园图默认开启滚轮缩放");
  await center();
  await page.screenshot({ path: "output/playwright/campus-map/overview-light.png" });
  const beforeWheel = await scale();
  const box = await page.locator(".plant-map").boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.wheel(0, -240);
  await page.waitForFunction(old => document.querySelector(".leaflet-control-scale-line").textContent !== old, beforeWheel);
  await settle();
  check(await noOverlap(), "放大后的楼名重新排布");
  const zoomedScale = await scale();
  const img = await page.locator(".campus-basemap").elementHandle();
  await theme("深色");
  check((await page.locator(".campus-basemap").getAttribute("src")).endsWith("campus-dark.svg"), "夜间加载独立石墨灰校园矢量图");
  check(await img.evaluate(el => el.isConnected) && await scale() === zoomedScale, "切换外观保留地图位置、缩放及图层实例");
  check(await page.locator(".leaflet-tile-pane").evaluate(el => getComputedStyle(el).filter === "none"), "校园图采用自身配色，不叠加在线地图滤镜");
  await center();
  await page.screenshot({ path: "output/playwright/campus-map/detail-dark.png" });
  await theme("跟随系统");
  await page.emulateMedia({ colorScheme: "dark" });
  await page.waitForFunction(() => document.querySelector(".campus-basemap")?.getAttribute("src")?.endsWith("campus-dark.svg"));
  check(true, "系统夜间切换同步校园图");
  await page.emulateMedia({ colorScheme: "light" });
  await page.waitForFunction(() => document.querySelector(".campus-basemap")?.getAttribute("src")?.endsWith("campus-light.svg"));
  await settle();
  check(true, "系统日间切换同步校园图");
  await page.getByRole("checkbox", { name: "植物点位" }).uncheck();
  await page.waitForFunction(() => {
    const c = document.querySelector(".plant-map canvas");
    return !c.getContext("2d").getImageData(0, 0, c.width, c.height).data.some((v, i) => i % 4 === 3 && v > 0);
  });
  check(await page.locator(".campus-basemap").isVisible() && await page.locator(".campus-landmark").count() > 0, "隐藏植物后保留道路、建筑和楼名");
  await center();
  await page.screenshot({ path: "output/playwright/campus-map/buildings-light.png" });
  await page.getByRole("checkbox", { name: "植物点位" }).check();
  await page.getByRole("button", { name: "在线地图", exact: true }).click();
  await page.waitForFunction(() => [...document.querySelectorAll(".leaflet-tile")].some(img => img.complete && img.naturalWidth > 0));
  check(await scale() === zoomedScale && !await page.locator(".campus-landmark").count(), "切换在线地图保留视野并卸载校园标签");
  await page.reload({ waitUntil: "domcontentloaded" });
  await page.locator(".plant-map canvas").waitFor();
  check(await page.getByRole("button", { name: "在线地图", exact: true }).getAttribute("aria-pressed") === "true", "刷新记住上次选择的在线地图");
  await page.getByRole("button", { name: "校园图", exact: true }).click();
  await settle();
  await page.getByRole("textbox", { name: "搜索地图植物" }).fill("红花碧桃");
  await page.waitForFunction(() => document.querySelector(".map-result-count")?.textContent?.includes("1 种 · 1 个点位"));
  await page.waitForTimeout(250);
  await center();
  await page.locator(".plant-map").click();
  await page.locator(".plant-popup").waitFor();
  check((await page.locator(".plant-popup strong").innerText()) === "红花碧桃" && (await page.locator(".plant-point-source").innerText()).includes("Q13"), "补充点位可搜索、点击，弹窗显示 PDF 来源与编号");
  const sourcePosition = await page.locator(".leaflet-popup").evaluate(el => el.style.transform);
  await page.getByRole("button", { name: "在线地图", exact: true }).click();
  check((await page.locator(".plant-popup strong").innerText()) === "红花碧桃" && await page.locator(".leaflet-popup").evaluate(el => el.style.transform) === sourcePosition, "在线地图显示同一补充点位，切换底图不移动坐标");
  await page.locator(".plant-popup a").click();
  await page.getByRole("heading", { name: "红花碧桃", exact: true }).waitFor();
  check((await page.locator(".plant-map canvas").count()) === 1, "补充植物可进入档案并显示分布");
  await page.getByRole("button", { name: "校园图", exact: true }).click();
  await settle();
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 844 });
    await page.getByRole("button", { name: "展开地图", exact: true }).click();
    await settle();
    const fit = await page.locator(".plant-map-shell").evaluate(shell => [...shell.querySelectorAll(".map-controls button,.map-options label")].every(el => {
      const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight;
    }));
    check(fit && await noOverlap(), width + "px 展开地图控件完整，楼名避让控件");
    await page.screenshot({ path: "output/playwright/campus-map/mobile-" + width + ".png" });
    await page.keyboard.press("Escape");
    check(!await page.getByRole("dialog").count(), width + "px Esc 正常收起");
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.route("**/maps/campus-light.svg", route => route.abort());
  await page.goto(root + "#/");
  await page.reload({ waitUntil: "domcontentloaded" });
  await page.getByRole("status").filter({ hasText: "校园图暂未加载" }).waitFor();
  check((await page.locator(".plant-map canvas").count()) === 1, "校园底图失败时保留植物点位并提示重试");
  await page.unroute("**/maps/campus-light.svg");
  await page.getByRole("button", { name: "重新加载", exact: true }).click();
  await settle();
  check(!await page.locator(".tile-notice").count(), "重新加载校园图后恢复并清除错误提示");
  await page.route("**/maps/campus-dark.svg", route => route.abort());
  await page.locator(".map-theme-switch").getByRole("button", { name: "深色", exact: true }).click();
  await page.getByRole("button", { name: "切换在线地图", exact: true }).click();
  check(await page.getByRole("button", { name: "在线地图", exact: true }).getAttribute("aria-pressed") === "true", "底图失败时可切换在线地图继续使用");
  await page.unroute("**/maps/campus-dark.svg");
  await page.locator(".map-theme-switch").getByRole("button", { name: "标准", exact: true }).click();
  await page.getByRole("button", { name: "校园图", exact: true }).click();
  await settle();
  await page.route("**/maps/campus-supplement.geojson", route => route.fulfill({ status: 503, body: "unavailable" }));
  await page.reload({ waitUntil: "domcontentloaded" });
  await page.getByRole("alert").waitFor();
  await page.unroute("**/maps/campus-supplement.geojson");
  await page.getByRole("button", { name: "重新加载", exact: true }).click();
  await settle();
  check((await page.locator(".map-result-count").innerText()).includes("16,440"), "补充数据失败后可重试，不重复合并点位");
  await center();
  await page.screenshot({ path: "output/playwright/campus-map/overview-final.png" });
  check(errors.length === 0, "页面未捕获异常为 0：" + errors.join("; "));
  return { passed: checks.length, checks };
}
